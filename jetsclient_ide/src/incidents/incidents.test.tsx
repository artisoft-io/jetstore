type Reply = { status?: number; body: unknown };

async function clientWith(
  script: Record<string, Reply | ((req: Record<string, unknown>) => Reply)>,
  capabilities: string[] = ["agent_supervision"],
) {
  const sent: Record<string, unknown>[] = [];
  const fetchImpl = vi.fn(async (url: string, init?: RequestInit) => {
    if (String(url).endsWith("/login")) {
      return new Response(
        JSON.stringify({
          token: "t0",
          name: "Supervisor",
          user_email: "supervisor@example.com",
          is_admin: false,
          capabilities,
        }),
        { status: 200 },
      );
    }
    const req = JSON.parse(String(init?.body ?? "{}")) as Record<string, unknown>;
    sent.push(req);
    const entry = script[String(req["action"])];
    const reply = typeof entry === "function" ? entry(req) : entry;
    if (!reply) return new Response(JSON.stringify({ error: "no script" }), { status: 500 });
    return new Response(JSON.stringify({ token: "t1", ...(reply.body as object) }), {
      status: reply.status ?? 200,
    });
  }) as unknown as typeof fetch;
  const api = new ApiClient("", fetchImpl);
  await api.login("supervisor@example.com", "pw");
  return { api, sent };
}

/**
 * Renders the shell's banner state so a test can read it (`AJ.2`).
 *
 * The real banner belongs to `App.tsx` and is not under test here, so without
 * this the two levels the shell exposes — `error` and `status` — are invisible
 * to every test in this file. That is what a verdict's confirmation and the 409
 * recovery are: the screen's whole visible answer is a banner, and a screen
 * whose only output nothing can assert is a screen with an untested output.
 */
function NotificationProbe() {
  const { error, status } = useNotifications();
  return <div data-testid="banner">{error ?? status ?? ""}</div>;
}

function renderAt(api: ApiClient, path: string) {
  return render(
    <ApiProvider api={api}>
      <NotificationsProvider>
        <NotificationProbe />
        <MemoryRouter initialEntries={[path]}>
          <Routes>
            <Route path="/incidents" element={<IncidentsScreen api={api} />} />
            <Route path="/incidents/:incidentId" element={<IncidentScreen api={api} />} />
          </Routes>
        </MemoryRouter>
      </NotificationsProvider>
    </ApiProvider>,
  );
}

